// Adds VEX's low profile (thin) nylock nut to the original's nut family: mesh baked in inches from the VEX-CAD model.
var fbx = UnityEditor.AssetDatabase.LoadAssetAtPath<GameObject>("Assets/Protobot/Parts/Models/Structure/Hardware/Nut Thin Nylock.fbx");
MeshFilter lod0 = null; foreach (var mf in fbx.GetComponentsInChildren<MeshFilter>(true)) if (mf.name.EndsWith("LOD0")) lod0 = mf;
var mesh = UnityEngine.Object.Instantiate(lod0.sharedMesh);
mesh.name = "Low Profile Nylock";
var v = mesh.vertices; for (int i = 0; i < v.Length; i++) v[i] *= 39.3701f; mesh.vertices = v; mesh.RecalculateBounds(); mesh.RecalculateTangents();
System.IO.Directory.CreateDirectory("Assets/ProtobotRebuilt/Models/V2");
var meshPath = "Assets/ProtobotRebuilt/Models/V2/Low Profile Nylock.asset";
UnityEditor.AssetDatabase.CreateAsset(mesh, meshPath);
var prefabPath = "Assets/ProtobotRebuilt/Resources/Part Prefabs/5Structure/Nut.prefab";
var root = UnityEditor.PrefabUtility.LoadPrefabContents(prefabPath);
var old = root.transform.Find("Low Profile Nylock"); if (old != null) UnityEngine.Object.DestroyImmediate(old.gameObject);
var template = root.transform.Find("Lock Nut");
var lowProfile = root.transform.Find("Low Profile");
var copy = UnityEngine.Object.Instantiate(template.gameObject, root.transform);
copy.name = "Low Profile Nylock";
copy.transform.SetSiblingIndex(lowProfile.GetSiblingIndex() + 1);
copy.transform.localPosition = template.localPosition; copy.transform.localRotation = template.localRotation; copy.transform.localScale = Vector3.one;
copy.GetComponent<MeshFilter>().sharedMesh = mesh;
copy.GetComponent<MeshCollider>().sharedMesh = mesh;
var steel = template.GetComponent<MeshRenderer>().sharedMaterial;
Material white = null;
foreach (var r in Resources.Load<GameObject>("Part Prefabs/VEX/Pneumatics").GetComponentsInChildren<MeshRenderer>(true)) foreach (var m in r.sharedMaterials) if (m != null && m.name == "White Plastic") white = m;
copy.GetComponent<MeshRenderer>().sharedMaterials = new[] { steel, white != null ? white : steel };
var data = copy.GetComponent<Protobot.PartData>(); data.param1Value = "Low Profile Nylock"; data.param2Value = "";
var pn = copy.GetComponent<Parts_List.PartName>(); pn.name = "Low Profile Nylock Nut"; pn.weightInGrams = 1.6f;
var hole = copy.GetComponentInChildren<Protobot.HoleCollider>(true).transform;
var depth = mesh.bounds.size.z;
hole.localPosition = new Vector3(0f, 0f, mesh.bounds.max.z - depth / 2f);
hole.localScale = new Vector3(0.135f, 0.135f, depth);
UnityEditor.PrefabUtility.SaveAsPrefabAsset(root, prefabPath);
UnityEditor.PrefabUtility.UnloadPrefabContents(root);
return "added: depth " + depth.ToString("F3") + " size " + mesh.bounds.size.ToString("F3") + " white " + (white != null);
