var camera = Protobot.PivotCamera.Main.camera;
var ui = UnityEngine.GameObject.Find("UICamera");
if (ui != null) ui.SetActive(false);
var rt = new UnityEngine.RenderTexture(2560, 1440, 24);
rt.antiAliasing = 8;
var old = camera.targetTexture;
camera.targetTexture = rt;
camera.Render();
camera.targetTexture = old;
if (ui != null) ui.SetActive(true);
UnityEngine.RenderTexture.active = rt;
var tex = new UnityEngine.Texture2D(2560, 1440, UnityEngine.TextureFormat.RGB24, false);
tex.ReadPixels(new UnityEngine.Rect(0, 0, 2560, 1440), 0, 0);
tex.Apply();
UnityEngine.RenderTexture.active = null;
var dir = "Assets/ProtobotRebuilt/Resources/Online/Backgrounds";
System.IO.Directory.CreateDirectory(dir);
System.IO.File.WriteAllBytes(dir + "/Override field.jpg", tex.EncodeToJPG(88));
rt.Release();
return "saved";
